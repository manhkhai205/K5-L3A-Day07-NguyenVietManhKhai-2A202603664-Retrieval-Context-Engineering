def export_chunks_from_qdrant(qdrant_url: str, collection_name: str, strategy: str = "B") -> list[dict[str, Any]]:
    """Fetch all strategy B chunks directly from the Day 6 Qdrant collection and sort deterministically."""
    client = QdrantClient(url=qdrant_url, timeout=30.0)
    points: list[Any] = []
    next_offset = None
    while True:
        batch, next_offset = client.scroll(
            collection_name=collection_name,
            scroll_filter=models.Filter(
                must=[
                    models.FieldCondition(
                        key="strategy",
                        match=models.MatchValue(value=strategy),
                    )
                ]
            ),
            limit=256,
            offset=next_offset,
            with_payload=True,
            with_vectors=False,
        )
        points.extend(batch)
        if next_offset is None:
            break

    raw_chunks: list[dict[str, Any]] = []
    for pt in points:
        payload = pt.payload or {}
        meta = {
            k: v
            for k, v in payload.items()
            if k not in {"strategy", "chunk_id", "document_id", "source", "page", "text"}
        }
        raw_chunks.append(
            {
                "chunk_id": payload["chunk_id"],
                "document_id": payload["document_id"],
                "source": payload["source"],
                "page": int(payload["page"]),
                "text": payload["text"],
                "metadata": meta,
            }
        )

    raw_chunks.sort(key=lambda c: (c["document_id"], c["page"], c["chunk_id"]))
    return raw_chunks


